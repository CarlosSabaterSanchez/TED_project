#Custom function to generate composition boxplot
composition_boxplot <- function(selected_pseq, selected_class, selected_title, selected_levels, x_cex, y_cex) {
  
  #Transform class to factor
  selected_pseq@sam_data[[selected_class]] <- factor(selected_pseq@sam_data[[selected_class]], levels=selected_levels)
  
  #Generate an OTU dataframe
  if (all(rownames(t(selected_pseq@otu_table)) == rownames(selected_pseq@sam_data)) == T) {
    #Append metadata label to OTU table
    selected_pseq_otu <- cbind.data.frame(selected_pseq@sam_data[[selected_class]], t(selected_pseq@otu_table))
    names(selected_pseq_otu)[1] <- selected_class
    #Remove numbers from taxa
    names(selected_pseq_otu) <- sub(".*[0-9]+_", "", names(selected_pseq_otu))
    names(selected_pseq_otu) <- gsub("_", " ",   names(selected_pseq_otu))
    #Sort taxa
    selected_pseq_otu <- selected_pseq_otu[,c(names(selected_pseq_otu)[1], sort(names(selected_pseq_otu)[2:length(names(selected_pseq_otu))]))]
    #Melt OTU table
    selected_pseq_otu_melt <- melt(selected_pseq_otu, id=selected_class)
    #Convert to factor
    selected_pseq_otu_melt[[selected_class]] <- factor(selected_pseq_otu_melt[[selected_class]],
                                                       selected_levels)
    #Generate multiple boxplots
    boxplot <- ggplot(selected_pseq_otu_melt, aes(x=variable, y=value, fill=eval(parse(text=selected_class)))) +
      geom_boxplot(alpha=0.3) +
      theme(legend.position="bottom", text=element_text(size=y_cex), axis.text.x=element_text(size=x_cex, angle=90, vjust=0.5, hjust=1, face="italic")) +
      xlab("") + ylab("Abundance (%)")
    #Format j multiple boxplots
    boxplot <- boxplot + 
      theme(panel.background=element_rect(fill='white', colour='black')) + labs(fill=selected_class, title=selected_title) # +
    # scale_y_continuous(labels = function(x) format(x, nsmall = 2)) + ylim(0, 1.0)
    
    #Generate individual boxplots
    boxplot_list <- list()
    #Iterate different taxa
    for (i in 2:ncol(selected_pseq_otu)) {
      #Get i taxa
      i_data <- selected_pseq_otu[,c(1,i)]
      #Generate i boxplot
      i_boxplot <- "NULL"
      i_boxplot <- ggplot(i_data, aes(x=.data[[selected_class]], y=i_data[,2], fill=.data[[selected_class]])) +
        geom_boxplot(alpha=0.3) +
        theme(legend.position="none", text=element_text(size=y_cex), axis.text.x=element_text(size=x_cex, angle=90, vjust=0.5, hjust=1)) +
        xlab("") + ylab(paste0(names(i_data)[2], " (%)"))
      i_boxplot <- i_boxplot + 
        theme(panel.background=element_rect(fill='white', colour='black')) + scale_fill_discrete(name="") #+
        # scale_y_continuous(labels = function(x) format(x, nsmall = 2)) #+ ylim(0, 1.0)
      #Store i boxplot
      print(i_boxplot)
      # i_results <- recordPlot()
      i_results <- ggplotGrob(i_boxplot) #To avoid overwritting
      boxplot_list[[length(boxplot_list)+1]] <- i_results
      names(boxplot_list)[[length(boxplot_list)]] <- names(i_data)[2] 
    }
    #Combine individual boxplots
    gridExtra:::grid.arrange(grobs=boxplot_list, ncol=length(boxplot_list))
    multiple_boxplots <- recordPlot()
    
    #Return results
    results <- list(selected_pseq_otu, boxplot, multiple_boxplots)
    names(results) <- c("data", "boxplot", "multiple_boxplots")
    return(results)
    
  }
}
  
