#Custom function to generate abundance barplot
abundance_barplot <- function(pseq_taxa, plot_level, metadata_class_no_formula, selected_levels) {
  
  #Transform class to factor
  pseq_taxa@sam_data[[metadata_class_no_formula]] <- factor(pseq_taxa@sam_data[[metadata_class_no_formula]], levels=selected_levels)
  
  #Plot most abundant taxa
  #Detection indicates the abundance threshold (in %) in at least one sample
  #Prevalence indicates the minimum number of samples showing that taxa
  #Select one taxonomic level for plotting (i.e. species)
  pseq_composition <- aggregate_taxa(pseq_taxa, plot_level)
  #Remove unknown taxa
  pseq_composition <- prune_taxa(grep("unknown", rownames(pseq_composition@otu_table),
                                      ignore.case=T, value=T, invert=T), pseq_composition)
  #Remove duplicated taxa generated by aggregate
  #Remove unknown taxa
  pseq_composition <- prune_taxa(grep("[|]", rownames(pseq_composition@otu_table),
                                      ignore.case=T, value=T, invert=T), pseq_composition)
  #Select core microbiota
  # pseq_composition <- core(pseq_composition, detection=1, prevalence=0)
  #Add unidentified taxa at that taxonomic level
  unidentified <- t(as.data.frame(100 - colSums(pseq_composition@otu_table), drop=F))
  rownames(unidentified) <- c("Other")
  if (length(unidentified) > 0) {
    pseq_composition@otu_table <- otu_table(rbind.data.frame(pseq_composition@otu_table, 
                                                             unidentified), taxa_are_rows=T)
  }
  #Order taxa by decreasing abundance
  taxa_order <- names(sort(rowMeans(pseq_composition@otu_table), decreasing=T))
  #Order taxa OTUs by decreasing abundance
  pseq_composition@otu_table <- pseq_composition@otu_table[taxa_order,]
  #Plot microbiome composition
  #Generate a custom palette for lots of taxa
  colourCount <- nrow(pseq_composition@otu_table)
  getPalette <- colorRampPalette(brewer.pal(9, "Set1"))
  #Limit the analysis on core taxa and specific sample group
  #Averaged by group
  #Remove numbers from microorganisms names for plotting
  rownames(pseq_composition@otu_table) <- gsub("_", " ", rownames(pseq_composition@otu_table))
  #Plot comparative graph
  composition_barplot <- plot_composition(pseq_composition, average_by = metadata_class_no_formula) +
    theme(text=element_text(size=23), legend.text = element_text(face="italic")) +
    xlab("") + ylab("Abundance (%)") + labs(fill="Taxonomic clades") +
    theme(panel.background=element_rect(fill='white', colour='black')) +
    scale_fill_manual(values=getPalette(colourCount))
  #scale_fill_brewer(palette="plasma")
  
  #Return results
  results <- list(composition_barplot)
  names(results) <- c("composition_barplot")
  return(results)
  
}
  
